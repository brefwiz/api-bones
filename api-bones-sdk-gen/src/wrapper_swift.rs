    /// A descriptor set whose `t.v1.Opts` message declares one string field
    /// per name, and the model of a client that takes it as its options.
    fn options_service(names: &[&str]) -> (Descriptors, Model) {
        use prost_reflect::prost_types::{
            DescriptorProto, FieldDescriptorProto, FileDescriptorProto, FileDescriptorSet,
            field_descriptor_proto::{Label, Type},
        };
        let fields = names
            .iter()
            .zip(1..)
            .map(|(name, number)| FieldDescriptorProto {
                name: Some((*name).to_owned()),
                json_name: Some((*name).to_owned()),
                number: Some(number),
                label: Some(Label::Optional as i32),
                r#type: Some(Type::String as i32),
                ..Default::default()
            })
            .collect();
        let set = FileDescriptorSet {
            file: vec![FileDescriptorProto {
                name: Some("t.proto".to_owned()),
                package: Some("t.v1".to_owned()),
                syntax: Some("proto3".to_owned()),
                message_type: vec![DescriptorProto {
                    name: Some("Opts".to_owned()),
                    field: fields,
                    ..Default::default()
                }],
                ..Default::default()
            }],
        };
        let descriptors = Descriptors {
            pool: DescriptorPool::from_file_descriptor_set(set).expect("a pool"),
        };
        let model = Model::from_source(
            "#[client(surface = \"s\", proto = generated::t::v1)]\n\
             impl Widgets { pub fn from_host(base_url: String, host: Host, \
             options: generated::t::v1::Opts) -> Result<Self, Error> { body() } }",
        )
        .expect("a model");
        (descriptors, model)
    }

    #[test]
    fn an_option_that_carries_a_root_pin_or_verifier_is_refused() {
        for name in [
            "caPem",
            "rootStore",
            "certChain",
            "pinSet",
            "verifier",
            "tlsConfig",
            "allowInsecure",
            "trustAnchor",
            "dangerousMode",
        ] {
            let (descriptors, model) = options_service(&[name]);
            let error = client_options(&descriptors, &model).expect_err("refused");
            assert!(
                error.to_string().contains(&format!("option `{name}`")),
                "{name}: {error}"
            );
            assert!(
                error.to_string().contains("takes no root, pin or verifier"),
                "{name}: {error}"
            );
        }
    }

    #[test]
    fn an_option_that_takes_the_name_of_an_entry_parameter_is_refused() {
        let (descriptors, model) = options_service(&["host"]);
        let error = client_options(&descriptors, &model).expect_err("refused");
        assert!(
            error
                .to_string()
                .contains("takes the name of an entry parameter")
        );
    }

    #[test]
    fn an_option_that_names_no_credential_is_listed() {
        let (descriptors, model) = options_service(&["defaultPageSize"]);
        let options = client_options(&descriptors, &model).expect("listed");
        assert_eq!(options.len(), 1);
        assert_eq!(options[0].0, "defaultPageSize");
    }

