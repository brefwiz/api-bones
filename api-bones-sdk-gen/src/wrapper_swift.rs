/// The uniffi functions and types the package names, as `(keyword, name)`.
fn declarations(model: &Model, service: &str) -> anyhow::Result<Vec<(&'static str, String)>> {
    let mut needed = vec![
        ("protocol", "FfiHost".to_owned()),
        ("enum", "FfiError".to_owned()),
        ("func", "formatError".to_owned()),
    ];
    let mut handle = false;
    for client in &model.clients {
        if !client.module {
            needed.push(("class", format!("{}Ffi", client.ty)));
        }
        for export in &client.exports {
            handle |= matches!(export.ret, Return::Handle { .. });
            needed.push((
                "func",
                typescript_name(&export_name(service, &client.ty, &export.method)?),
            ));
        }
    }
    if handle {
        needed.push(("class", "FfiHandle".to_owned()));
    }
    Ok(needed)
}

/// Whether `text` declares `name` with `keyword`: `func name`, `class Name`.
fn declares(text: &str, keyword: &str, name: &str) -> bool {
    let needle = format!("{keyword} {name}");
    text.match_indices(needle.as_str()).any(|(at, hit)| {
        text[at + hit.len()..]
            .chars()
            .next()
            .is_none_or(|next| !(next.is_alphanumeric() || next == '_'))
    })
}

/// Every uniffi function and type the package calls is declared by the
/// bindings, so a rename in the bindgen output fails here and not in a
/// consumer's build.
///
/// # Errors
///
/// The names the bindings do not declare.
fn check_bindings(model: &Model, service: &str, bindings: &[File]) -> anyhow::Result<()> {
    let text: String = bindings.iter().map(|(_, text)| text.as_str()).collect();
    let missing: Vec<String> = declarations(model, service)?
        .into_iter()
        .filter(|(keyword, name)| !declares(&text, keyword, name))
        .map(|(keyword, name)| format!("{keyword} {name}"))
        .collect();
    ensure!(
        missing.is_empty(),
        "the uniffi bindings do not declare what the package calls: {}",
        missing.join(", ")
    );
    Ok(())
}

/// Every file of the package, in path order.
///
/// # Errors
///
/// A name that cannot be spelled, an export no `l2_methods` entry lists, a
/// message the descriptor set lacks or declares other than the export's
/// parameters, and a call the bindings do not declare.
fn generate(
    model: &Model,
    package: &Package,
    descriptors: &Descriptors,
    bindings: &[File],
) -> anyhow::Result<Vec<File>> {
    let document = l2_methods(
        model,
        &package.spec,
        &package.service,
        &package.crate_name,
        &package.name,
    )?;
    check_bindings(model, &package.service, bindings)?;
    let module = package.name.as_str();
    let error = format!("{}Error", service_pascal(&package.service));
    let ctx = Ctx {
        descriptors,
        service: &package.service,
        error: error.clone(),
    };
    let rendered = client_swift(&ctx, model, &document, module)?;
    let sources = format!("Sources/{module}");
    let mut files = vec![
        ("Package.swift".to_owned(), package_swift(module)),
        ("buf.gen.yaml".to_owned(), buf_gen(module)),
        ("l2-methods.json".to_owned(), document.to_json()),
        ("api-surface.swift.txt".to_owned(), rendered.surface),
        (
            format!("{sources}/{}Client.swift", service_pascal(&package.service)),
            rendered.client,
        ),
        (
            format!("{sources}/Errors.swift"),
            errors_swift(model, module, &error),
        ),
        (
            format!("{sources}/Pages.swift"),
            pages_swift(module, &error),
        ),
    ];
    for (path, text) in bindings {
        files.push((format!("Sources/{module}FFI/{path}"), text.clone()));
    }
    files.sort();
    Ok(files)
}

