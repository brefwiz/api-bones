/// What the generator is told about the package it writes.
struct Package {
    /// The SPEC `service`.
    service: String,
    /// The Layer 2 crate.
    crate_name: String,
    /// The Swift package, which is also the name of its module.
    name: String,
    /// The `sdk_surfaces` the exports name, and each endpoint's Rust methods.
    spec: SpecL2Methods,
    /// The surfaces whose swift targets list the package, each with the
    /// endpoints its `l2_methods` names.
    listed: BTreeMap<String, Vec<String>>,
}

/// Writes the Swift package of the Layer 2 crate at `krate` into `out`.
///
/// `bindings` is the directory the uniffi bindgen wrote; every file under it
/// is copied into the FFI target as it is.
///
/// # Errors
///
/// Any refusal of [`package_of`], [`bindings_of`] or [`generate`], and an I/O
/// error.
pub(crate) fn run(
    krate: &Path,
    spec: &Path,
    out: &Path,
    descriptor: &Path,
    bindings: Option<PathBuf>,
) -> anyhow::Result<()> {
    let bindings = bindings.ok_or_else(|| {
        anyhow!("`wrapper swift` copies the uniffi output: pass `--bindings <dir>`")
    })?;
    let text =
        std::fs::read_to_string(spec).with_context(|| format!("cannot read {}", spec.display()))?;
    let manifest = krate.join("Cargo.toml");
    let manifest = std::fs::read_to_string(&manifest)
        .with_context(|| format!("cannot read {}", manifest.display()))?;
    let model = crate::features::read_model(krate)?;
    let package = package_of(&text, &crate_name(&manifest)?, &model)?;
    let descriptors = Descriptors::read(descriptor)?;
    let copied = bindings_of(&bindings)?;
    crate::wrapper_ts::write(out, &generate(&model, &package, &descriptors, &copied)?)
}

/// What the SPEC front matter and the crate's name say about the package.
///
/// The package is the one `targets.swift.packages` entry the surfaces share:
/// one crate, one wrapper, one package.
///
/// # Errors
///
/// A SPEC without front matter, service or surfaces; zero or several swift
/// packages; a package that is no Swift module name; an export of a surface
/// that does not list the package; a surface that lists it and names an
/// endpoint no export serves.
fn package_of(spec: &str, crate_name: &str, model: &Model) -> anyhow::Result<Package> {
    let front = spec
        .strip_prefix("---\n")
        .and_then(|rest| rest.split("\n---").next())
        .ok_or_else(|| anyhow!("the SPEC has no front matter"))?;
    let document: serde_yaml::Value = serde_yaml::from_str(front)?;
    let service = document["service"]
        .as_str()
        .ok_or_else(|| anyhow!("the SPEC names no service"))?
        .to_owned();
    let surfaces = document["sdk_surfaces"]
        .as_mapping()
        .ok_or_else(|| anyhow!("the SPEC lists no sdk_surfaces"))?;
    let named: BTreeSet<String> = surfaces
        .values()
        .flat_map(|entry| strings(&entry["targets"]["swift"]["packages"]))
        .collect();
    ensure!(
        !named.is_empty(),
        "no sdk_surfaces entry lists a swift target package"
    );
    ensure!(
        named.len() == 1,
        "the swift targets list {} packages ({}); one crate is one package",
        named.len(),
        named.iter().cloned().collect::<Vec<_>>().join(", ")
    );
    let name = named.into_iter().next().expect("one package");
    ensure!(
        is_module_name(&name),
        "`{name}` cannot name a Swift module: it starts with a letter and holds letters, digits and `_`"
    );
    let mut spec_l2 = SpecL2Methods::default();
    let mut listed = BTreeMap::new();
    for (id, entry) in surfaces {
        let id = id.as_str().unwrap_or_default().to_owned();
        spec_l2.surfaces.insert(id.clone());
        if !strings(&entry["targets"]["swift"]["packages"]).contains(&name) {
            continue;
        }
        let mut endpoints = Vec::new();
        let by_endpoint = spec_l2.endpoints.entry(id.clone()).or_default();
        if let Some(mapping) = entry["l2_methods"].as_mapping() {
            for (endpoint, languages) in mapping {
                let endpoint = endpoint.as_str().unwrap_or_default().to_owned();
                by_endpoint.insert(endpoint.clone(), strings(&languages["rust"]));
                endpoints.push(endpoint);
            }
        }
        listed.insert(id, endpoints);
    }
    let package = Package {
        service,
        crate_name: crate_name.to_owned(),
        name,
        spec: spec_l2,
        listed,
    };
    verify(model, &package)?;
    Ok(package)
}

/// The strings of a YAML sequence; anything else holds none.
fn strings(value: &serde_yaml::Value) -> Vec<String> {
    value
        .as_sequence()
        .into_iter()
        .flatten()
        .filter_map(|item| item.as_str())
        .map(str::to_owned)
        .collect()
}

fn is_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// The `name` of the `[package]` table of a crate manifest.
fn crate_name(manifest: &str) -> anyhow::Result<String> {
    let mut in_package = false;
    for line in manifest.lines().map(str::trim) {
        if line.starts_with('[') {
            in_package = line == "[package]";
        } else if in_package
            && let Some(value) = line
                .strip_prefix("name")
                .and_then(|rest| rest.trim_start().strip_prefix('='))
            && let Some(quoted) = value.trim().strip_prefix('"')
            && let Some(name) = quoted.split('"').next()
        {
            return Ok(name.to_owned());
        }
    }
    Err(anyhow!("the crate manifest has no `[package]` name"))
}

/// Every export names a surface that lists the package, and every endpoint of
/// every surface that lists it is served by an export of the crate.
fn verify(model: &Model, package: &Package) -> anyhow::Result<()> {
    for client in &model.clients {
        for export in &client.exports {
            ensure!(
                package.listed.contains_key(&export.surface),
                "package `{}` is not a swift target of surface `{}`, which the exports of `{}` name",
                package.name,
                export.surface,
                package.crate_name
            );
        }
    }
    let document = l2_methods(
        model,
        &package.spec,
        &package.service,
        &package.crate_name,
        &package.name,
    )?;
    for (surface, endpoints) in &package.listed {
        for endpoint in endpoints {
            ensure!(
                document
                    .methods
                    .iter()
                    .any(|method| method.surface == *surface && method.endpoints.contains(endpoint)),
                "surface `{surface}` lists package `{}` and names endpoint `{endpoint}`, which no export of `{}` serves",
                package.name,
                package.crate_name
            );
        }
    }
    Ok(())
}

/// The uniffi bindgen output under `dir`: each file by its path relative to
/// `dir`, in path order.
///
/// # Errors
///
/// A directory that cannot be read, holds no file, or holds one that is not
/// UTF-8 text.
fn bindings_of(dir: &Path) -> anyhow::Result<Vec<File>> {
    let mut files = Vec::new();
    collect(dir, dir, &mut files)?;
    ensure!(
        !files.is_empty(),
        "the bindings directory {} holds no file",
        dir.display()
    );
    files.sort();
    Ok(files)
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<File>) -> anyhow::Result<()> {
    let entries =
        std::fs::read_dir(dir).with_context(|| format!("cannot read {}", dir.display()))?;
    for entry in entries {
        let path = entry?.path();
        if path.is_dir() {
            collect(root, &path, out)?;
        } else {
            let text = std::fs::read_to_string(&path)
                .with_context(|| format!("cannot read {} as text", path.display()))?;
            let relative = path.strip_prefix(root)?;
            out.push((relative.to_string_lossy().replace('\\', "/"), text));
        }
    }
    Ok(())
}

/// The file descriptor set that declares every message the exports cross as.
#[derive(Debug)]
struct Descriptors {
    pool: DescriptorPool,
}

impl Descriptors {
    /// Reads the descriptor set at `path`.
    fn read(path: &Path) -> anyhow::Result<Self> {
        let bytes = std::fs::read(path)
            .with_context(|| format!("cannot read the descriptor set {}", path.display()))?;
        Self::decode(&bytes).with_context(|| format!("invalid descriptor set {}", path.display()))
    }

    fn decode(bytes: &[u8]) -> anyhow::Result<Self> {
        let pool = DescriptorPool::decode(bytes)?;
        ensure!(pool.files().next().is_some(), "the descriptor set is empty");
        Ok(Self { pool })
    }

    fn message(&self, full_name: &str) -> anyhow::Result<MessageDescriptor> {
        // A set built from the contract protos alone leaves out a well-known
        // type no proto imports, such as the `Empty` of a zero-argument export.
        self.pool
            .get_message_by_name(full_name)
            .or_else(|| DescriptorPool::global().get_message_by_name(full_name))
            .ok_or_else(|| anyhow!("message `{full_name}` is missing from the descriptor set"))
    }
}

/// `Contract_Sdk_V1_` for the package `contract.sdk.v1`: how protoc-gen-swift
/// prefixes the types of a package.
fn swift_prefix(package: &str) -> String {
    if package.is_empty() {
        return String::new();
    }
    let parts: Vec<String> = package
        .split('.')
        .map(|segment| segment.split('_').map(upper_first).collect())
        .collect();
    format!("{}_", parts.join("_"))
}

fn upper_first(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_uppercase().chain(chars).collect())
        .unwrap_or_default()
}

fn lower_first(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_lowercase().chain(chars).collect())
        .unwrap_or_default()
}

/// `Svc` of the service `svc`, as a type-name prefix.
fn service_pascal(service: &str) -> String {
    service
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(upper_first)
        .collect()
}

/// The Swift type protoc-gen-swift writes for `message`; a nested message is
/// nested in the Swift type of its parent.
fn swift_message(message: &MessageDescriptor) -> String {
    match message.parent_message() {
        Some(parent) => format!("{}.{}", swift_message(&parent), message.name()),
        None => format!("{}{}", swift_prefix(message.package_name()), message.name()),
    }
}

fn swift_enum(value: &EnumDescriptor) -> String {
    match value.parent_message() {
        Some(parent) => format!("{}.{}", swift_message(&parent), value.name()),
        None => format!("{}{}", swift_prefix(value.package_name()), value.name()),
    }
}

fn swift_ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_owned()
    }
}

fn kind_swift(kind: &Kind) -> String {
    match kind {
        Kind::Bool => "Bool".to_owned(),
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 => "Int32".to_owned(),
        Kind::Uint32 | Kind::Fixed32 => "UInt32".to_owned(),
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 => "Int64".to_owned(),
        Kind::Uint64 | Kind::Fixed64 => "UInt64".to_owned(),
        Kind::Float => "Float".to_owned(),
        Kind::Double => "Double".to_owned(),
        Kind::String => "String".to_owned(),
        Kind::Bytes => "Data".to_owned(),
        Kind::Message(message) => swift_message(message),
        Kind::Enum(value) => swift_enum(value),
    }
}

/// The Swift type of the property protoc-gen-swift writes for `field`.
fn field_swift(field: &FieldDescriptor) -> String {
    if let (true, Kind::Message(entry)) = (field.is_map(), field.kind()) {
        return format!(
            "[{}: {}]",
            kind_swift(&entry.map_entry_key_field().kind()),
            kind_swift(&entry.map_entry_value_field().kind())
        );
    }
    let ty = kind_swift(&field.kind());
    if field.is_list() {
        format!("[{ty}]")
    } else {
        ty
    }
}

/// One parameter of a method, bound to the field of the args message it
/// travels in.
struct Arg {
    /// The field's camel case name, which is also the Swift label.
    name: String,
    ty: String,
    /// A field declared `optional` in proto: the parameter defaults to nil and
    /// the field is set only when it is given.
    optional: bool,
}

/// The Swift type of the args message of `export` and its parameters bound to
/// the fields of that message, in parameter order.
///
/// # Errors
///
/// An args message the descriptor set lacks, one whose field names are not
/// exactly the parameter names, a zero-parameter export whose args are not
/// `google.protobuf.Empty`, or a parameter that cannot be spelled safely.
fn args_of(descriptors: &Descriptors, export: &Export) -> anyhow::Result<(String, Vec<Arg>)> {
    let args = export.args.full_name();
    let message = descriptors.message(args)?;
    let at = || format!("`{}` (args `{args}`)", export.method);
    if export.params.is_empty() {
        ensure!(
            args == "google.protobuf.Empty",
            "{} takes no parameter, so its args are `google.protobuf.Empty`",
            at()
        );
    }
    let wanted: BTreeSet<String> = export.params.iter().map(Param::json_name).collect();
    let declared: BTreeSet<String> = message.fields().map(|f| f.json_name().to_owned()).collect();
    ensure!(
        wanted == declared,
        "{}: the message declares fields {declared:?} but the parameters are {wanted:?}",
        at()
    );
    let mut bound = Vec::new();
    for param in &export.params {
        let name = param.json_name();
        ensure!(
            !LOCALS.contains(&name.as_str()) && !KEYWORDS.contains(&name.as_str()),
            "{}: parameter `{name}` takes a name Swift or the generated body owns",
            at()
        );
        let field = message
            .fields()
            .find(|f| f.json_name() == name)
            .ok_or_else(|| anyhow!("{}: no field `{name}`", at()))?;
        bound.push(Arg {
            ty: field_swift(&field),
            optional: field
                .field_descriptor_proto()
                .proto3_optional
                .unwrap_or(false),
            name,
        });
    }
    Ok((swift_message(&message), bound))
}

/// The Swift type and the expression that reads a value out of the message
/// bytes `bytes` of `wire`: a scalar wrapper is unwrapped to its value,
/// `Timestamp` and `Duration` stay the SwiftProtobuf well-known messages, and
/// `Empty` is no value.
fn decoded(
    descriptors: &Descriptors,
    wire: &Wire,
    bytes: &str,
) -> anyhow::Result<Option<(String, String)>> {
    if matches!(wire, Wire::Empty) {
        return Ok(None);
    }
    let name = swift_message(&descriptors.message(wire.full_name())?);
    let read = format!("try {name}(serializedBytes: {bytes})");
    Ok(Some(match wire {
        Wire::Wrapper(wrapper) => {
            let scalar = match wrapper {
                Wrapper::Bool => "Bool",
                Wrapper::Int32 => "Int32",
                Wrapper::UInt32 => "UInt32",
                Wrapper::Int64 => "Int64",
                Wrapper::UInt64 => "UInt64",
                Wrapper::Double => "Double",
                Wrapper::String => "String",
                Wrapper::Bytes => "Data",
                Wrapper::Timestamp | Wrapper::Duration => return Ok(Some((name, read))),
            };
            (scalar.to_owned(), format!("{read}.value"))
        }
        _ => (name, read),
    }))
}

/// The message `item` of a list, batch or stream: those handles decode through
/// the item's message, so the item is a generated message.
fn item_of(descriptors: &Descriptors, item: &Wire, at: &str) -> anyhow::Result<String> {
    ensure!(
        matches!(item, Wire::Message(_)),
        "{at}: a list, batch or stream yields a generated message, not `{}`",
        item.full_name()
    );
    Ok(swift_message(&descriptors.message(item.full_name())?))
}

/// What the methods are rendered against.
struct Ctx<'a> {
    descriptors: &'a Descriptors,
    /// The SPEC `service`.
    service: &'a str,
    /// The name of the error type every call throws.
    error: String,
}

/// One method of a generated client.
struct Method {
    /// The member, indented as in a type body.
    text: String,
    /// The declaration, as the surface lists it.
    signature: String,
}

/// The lines that build `request` from the parameters, at indentation `ind`.
fn request_lines(message: &str, args: &[Arg], ind: &str) -> String {
    if args.is_empty() {
        return format!("{ind}let request = try {message}().serializedData()\n");
    }
    let mut out = format!("{ind}var args = {message}()\n");
    for arg in args {
        let name = &arg.name;
        if arg.optional {
            let _ = writeln!(out, "{ind}if let {name} {{ args.{name} = {name} }}");
        } else {
            let _ = writeln!(out, "{ind}args.{name} = {name}");
        }
    }
    let _ = writeln!(out, "{ind}let request = try args.serializedData()");
    out
}

/// The `do` block that makes `call` and answers what it reads, with the
/// error mapped, at indentation `ind`.
fn guarded(ind: &str, error: &str, call: &str, read: Option<&str>) -> String {
    let body = match read {
        Some(expr) => format!("{ind}    let bytes = {call}\n{ind}    return {expr}\n"),
        None => format!("{ind}    _ = {call}\n"),
    };
    format!("{ind}do {{\n{body}{ind}}} catch {{\n{ind}    throw {error}.mapped(error)\n{ind}}}\n")
}

/// The Swift member for `export`, indented as in a type body.
///
/// # Errors
///
/// As [`args_of`], a list, batch or stream item that is not a generated
/// message, and a constant that yields no value.
fn method_swift(ctx: &Ctx<'_>, client: &Client, export: &Export) -> anyhow::Result<Method> {
    let descriptors = ctx.descriptors;
    let name = swift_ident(&typescript_name(&export.method));
    let (message, args) = args_of(descriptors, export)?;
    let function = typescript_name(&export_name(ctx.service, &client.ty, &export.method)?);
    let call = match export.shape {
        Shape::Method => format!("{function}(client: ffi, req: request)"),
        Shape::Function => format!("{function}(req: request)"),
        Shape::Constant => format!("{function}()"),
    };
    let params: Vec<String> = args
        .iter()
        .map(|arg| {
            if arg.optional {
                format!("{}: {}? = nil", arg.name, arg.ty)
            } else {
                format!("{}: {}", arg.name, arg.ty)
            }
        })
        .collect();
    let params = params.join(", ");
    let qualifier = if export.shape == Shape::Method {
        ""
    } else {
        "static "
    };
    let at = format!("`{}`", export.method);
    let request = request_lines(&message, &args, "        ");
    if let Return::Handle { kind, item } = &export.ret {
        let item_ty = item_of(descriptors, item, &at)?;
        let (out, open, decode) = match kind {
            HandleKind::List => (
                format!("Page<{item_ty}>"),
                format!("try {call}"),
                format!("try decodePage(bytes, as: {item_ty}.self)"),
            ),
            HandleKind::Stream => (
                item_ty.clone(),
                format!("try await {call}"),
                format!("try {item_ty}(serializedBytes: bytes)"),
            ),
            HandleKind::Batch => (
                format!("[BatchItem<{item_ty}>]"),
                format!("try {call}"),
                format!("try decodeBatchChunk(bytes, as: {item_ty}.self)"),
            ),
        };
        let header =
            format!("public {qualifier}func {name}({params}) -> AsyncThrowingStream<{out}, Error>");
        let open_request = request_lines(&message, &args, "                ");
        let capture = if export.shape == Shape::Method {
            "        let ffi = self.ffi\n"
        } else {
            ""
        };
        let text = format!(
            "    {header} {{\n{capture}        return streamOf(\n            open: {{\n{open_request}                return {open}\n            }},\n            decode: {{ bytes in {decode} }}\n        )\n    }}\n"
        );
        return Ok(Method {
            text,
            signature: format!("    {header}\n"),
        });
    }
    let wire = match &export.ret {
        Return::Value(wire) | Return::Result { ok: wire, .. } => Some(wire),
        Return::Unit | Return::Handle { .. } => None,
    };
    let is_async = !export.sync;
    let read = match wire {
        Some(wire) => decoded(descriptors, wire, "bytes")?,
        None => None,
    };
    let guard_call = if is_async {
        format!("try await {call}")
    } else {
        format!("try {call}")
    };
    let expr = read.as_ref().map(|(_, expr)| expr.as_str());
    if export.shape == Shape::Constant {
        let (ty, _) = read
            .as_ref()
            .ok_or_else(|| anyhow!("{at}: a constant yields a value"))?;
        let guard = guarded("            ", &ctx.error, &guard_call, expr);
        let header = format!("public static var {name}: {ty} {{ get throws }}");
        let text = format!(
            "    public static var {name}: {ty} {{\n        get throws {{\n{guard}        }}\n    }}\n"
        );
        return Ok(Method {
            text,
            signature: format!("    {header}\n"),
        });
    }
    let effects = if is_async { "async throws" } else { "throws" };
    let ret = read
        .as_ref()
        .map(|(ty, _)| format!(" -> {ty}"))
        .unwrap_or_default();
    let header = format!("public {qualifier}func {name}({params}) {effects}{ret}");
    let guard = guarded("        ", &ctx.error, &guard_call, expr);
    Ok(Method {
        text: format!("    {header} {{\n{request}{guard}    }}\n"),
        signature: format!("    {header}\n"),
    })
}

/// The options the clients' options messages declare, as one list in order of
/// first appearance: the name, its Swift type.
///
/// # Errors
///
/// An options message the descriptor set lacks, an option that takes the name
/// of an entry parameter, an option whose name says it carries a root, a
/// certificate, a pin, a verifier, a TLS setting or a trust decision, or one
/// name with two types.
fn client_options(
    descriptors: &Descriptors,
    model: &Model,
) -> anyhow::Result<Vec<(String, String)>> {
    let mut union: Vec<(String, String)> = Vec::new();
    for client in &model.clients {
        let Some(options) = &client.options else {
            continue;
        };
        for field in descriptors.message(&options.full_name)?.fields() {
            let name = field.json_name().to_owned();
            ensure!(
                name != "baseUrl" && name != "host",
                "option `{name}` of `{}` takes the name of an entry parameter",
                client.ty
            );
            let lowered = name.to_lowercase();
            if let Some(word) = FORBIDDEN_OPTION_WORDS
                .iter()
                .find(|word| lowered.contains(**word))
            {
                return Err(anyhow!(
                    "option `{name}` of `{}` names `{word}`: the package takes no root, pin or verifier, so an option cannot carry one",
                    client.ty
                ));
            }
            let ty = field_swift(&field);
            match union.iter().find(|(seen, _)| *seen == name) {
                Some((_, seen)) if *seen != ty => {
                    return Err(anyhow!(
                        "option `{name}` of `{}` is `{ty}` but another client takes it as `{seen}`",
                        client.ty
                    ));
                }
                Some(_) => {}
                None => union.push((name, ty)),
            }
        }
    }
    Ok(union)
}

/// What the client file is made of, and the surface lists.
struct Rendered {
    /// `<Svc>Client.swift`.
    client: String,
    /// The declarations of the surface, in file order.
    surface: String,
}

/// The names the generated package declares itself, which a client cannot
/// take.
fn taken(service: &str) -> [String; 8] {
    [
        format!("{service}Error"),
        format!("{service}Sdk"),
        format!("{service}SdkOptions"),
        "Page".to_owned(),
        "Total".to_owned(),
        "BatchItem".to_owned(),
        "FormattedError".to_owned(),
        "FormatErrorOptionError".to_owned(),
    ]
}

/// `<Svc>Client.swift`, with the surface of what it declares.
///
/// # Errors
///
/// As [`method_swift`] and [`client_options`], an async export `l2-methods`
/// does not list, and a client named as a type the package declares.
fn client_swift(
    ctx: &Ctx<'_>,
    model: &Model,
    document: &api_bones_sdk_model::L2Methods,
    module: &str,
) -> anyhow::Result<Rendered> {
    let listed: BTreeSet<&str> = document.methods.iter().map(|m| m.export.as_str()).collect();
    let union = client_options(ctx.descriptors, model)?;
    let service = service_pascal(ctx.service);
    let sdk = format!("{service}Sdk");
    let options_ty = format!("{sdk}Options");
    let reserved = taken(&service);
    let mut classes: Vec<String> = Vec::new();
    let mut surface_classes: Vec<String> = Vec::new();
    let mut fields = String::new();
    let mut construct = String::new();
    for client in &model.clients {
        let ty = &client.ty;
        ensure!(
            !reserved.contains(ty),
            "the client `{ty}` takes a name the package declares"
        );
        let mut blocks: Vec<String> = Vec::new();
        let mut surface = String::new();
        if !client.module {
            blocks.push(init_swift(ctx, client, &options_ty)?);
        }
        for export in &client.exports {
            let wasm_name = export_name(ctx.service, ty, &export.method)?;
            if !export.sync && !listed.contains(wasm_name.as_str()) {
                return Err(anyhow!("`{wasm_name}` is not in l2-methods"));
            }
            let method = method_swift(ctx, client, export)?;
            blocks.push(method.text);
            surface.push_str(&method.signature);
        }
        let body = blocks.join("\n");
        if client.module {
            classes.push(format!("public enum {ty} {{\n{body}}}\n"));
            surface_classes.push(format!("public enum {ty} {{\n{surface}}}\n"));
            continue;
        }
        classes.push(format!(
            "public final class {ty}: Sendable {{\n    private let ffi: {ty}Ffi\n\n{body}}}\n"
        ));
        surface_classes.push(format!(
            "public final class {ty}: Sendable {{\n{surface}}}\n"
        ));
        let property = lower_first(ty);
        let _ = writeln!(fields, "    public let {property}: {ty}");
        let options = if client.options.is_some() {
            ", options: options"
        } else {
            ""
        };
        let _ = writeln!(
            construct,
            "        {property} = try {ty}(baseUrl: baseUrl, host: host{options})"
        );
    }
    let entry_params = if union.is_empty() {
        String::new()
    } else {
        format!(", options: {options_ty} = {options_ty}()")
    };
    let entry_header = format!("public init(baseUrl: String, host: FfiHost{entry_params}) throws");
    let sdk_decl = format!(
        "/// Every client of the service, opened from one host.\npublic struct {sdk}: Sendable {{\n{fields}\n    /// Opens every client of the service against `baseUrl`; `host` answers the credential, anonymous and span requests of their calls.\n    {entry_header} {{\n{construct}    }}\n}}\n"
    );
    let surface_sdk = format!("public struct {sdk}: Sendable {{\n{fields}    {entry_header}\n}}\n");
    let mut blocks: Vec<String> = Vec::new();
    let mut surface_blocks: Vec<String> = Vec::new();
    if !union.is_empty() {
        let mut declared = String::new();
        let mut inits = Vec::new();
        let mut assigns = String::new();
        for (name, ty) in &union {
            let _ = writeln!(declared, "    public var {name}: {ty}?");
            inits.push(format!("{name}: {ty}? = nil"));
            let _ = writeln!(assigns, "        self.{name} = {name}");
        }
        let inits = inits.join(", ");
        blocks.push(format!(
            "/// What the entry takes besides the server's address and the host: the options of its clients.\npublic struct {options_ty}: Sendable {{\n{declared}\n    public init({inits}) {{\n{assigns}    }}\n}}\n"
        ));
        surface_blocks.push(format!(
            "public struct {options_ty}: Sendable {{\n{declared}    public init({inits})\n}}\n"
        ));
    }
    blocks.push(sdk_decl);
    surface_blocks.push(surface_sdk);
    blocks.extend(classes);
    surface_blocks.extend(surface_classes);
    let error = &ctx.error;
    surface_blocks.push(format!(
        "public func formatError(_ error: {error}, locale: String, timeZone: String? = nil) throws -> FormattedError\n"
    ));
    let mut client = String::from(HEADER);
    let _ = write!(
        client,
        "import Foundation\nimport {module}FFI\nimport SwiftProtobuf\n\n{}",
        blocks.join("\n")
    );
    let mut surface = String::from(HEADER);
    let _ = write!(surface, "\n{}", surface_blocks.join("\n"));
    Ok(Rendered { client, surface })
}

/// The constructor of a client: the server's address and the host go to the
/// FFI object's constructor, with the options the client's options message
/// declares.
///
/// # Errors
///
/// An options message the descriptor set lacks.
fn init_swift(ctx: &Ctx<'_>, client: &Client, options_ty: &str) -> anyhow::Result<String> {
    let ty = &client.ty;
    let error = &ctx.error;
    let Some(options) = &client.options else {
        return Ok(format!(
            "    init(baseUrl: String, host: FfiHost) throws {{\n        do {{\n            ffi = try {ty}Ffi(baseUrl: baseUrl, host: host, options: Data())\n        }} catch {{\n            throw {error}.mapped(error)\n        }}\n    }}\n"
        ));
    };
    let message = ctx.descriptors.message(&options.full_name)?;
    let mut sets = String::new();
    for field in message.fields() {
        let name = field.json_name();
        let _ = writeln!(
            sets,
            "        if let {name} = options.{name} {{ message.{name} = {name} }}"
        );
    }
    Ok(format!(
        "    init(baseUrl: String, host: FfiHost, options: {options_ty}) throws {{\n        var message = {}()\n{sets}        do {{\n            ffi = try {ty}Ffi(baseUrl: baseUrl, host: host, options: try message.serializedData())\n        }} catch {{\n            throw {error}.mapped(error)\n        }}\n    }}\n",
        swift_message(&message)
    ))
}

/// The module that holds what every file of the package shares: the error a
/// call throws and the text of an error for a person. `@ERROR@` and `@FFI@`
/// are replaced.
const ERRORS_SWIFT: &str = r#"
/// What a call of the service throws: the `bones.sdk.v1.CallError` the native layer answered, decoded once.
public enum @ERROR@: Error, Sendable {
    /// The call failed; `code` and `platform` say why. The `message` is never shown to a person: `formatError` renders the text.
    case call(Bones_Sdk_V1_CallError, bytes: Data)
    /// The native layer answered bytes that are no `CallError`.
    case undecodable(bytes: Data)

    /// The bytes the native layer answered, which `formatError` takes.
    public var bytes: Data {
        switch self {
        case let .call(_, bytes), let .undecodable(bytes):
            return bytes
        }
    }

    /// `error` as the call failure it is, or `error` itself when it did not come from the native layer.
    static func mapped(_ error: Error) -> Error {
        guard let failure = error as? FfiError else {
            return error
        }
        switch failure {
        case let .call(bytes):
            if let decoded = try? Bones_Sdk_V1_CallError(serializedBytes: bytes) {
                return @ERROR@.call(decoded, bytes: bytes)
            }
            return @ERROR@.undecodable(bytes: bytes)
        }
    }
}

/// A call error as text for a person.
public struct FormattedError: Sendable {
    /// The text, in the locale negotiated.
    public let text: String
    /// What the person can do about it, when the catalog has a hint.
    public let hint: String?
}

/// `formatError` refused an option; `rule` names which, such as `unknown_time_zone`.
public struct FormatErrorOptionError: Error, Sendable {
    public let rule: String
}

/// `error` rendered in `locale` with times in `timeZone` (UTC when nil). The only error it throws is `FormatErrorOptionError`.
public func formatError(_ error: @ERROR@, locale: String, timeZone: String? = nil) throws -> FormattedError {
    let answer = @FFI@.formatError(err: error.bytes, locale: locale, timeZone: timeZone)
    guard let result = try? Bones_Sdk_V1_FormatResult(serializedBytes: answer), let outcome = result.result else {
        throw FormatErrorOptionError(rule: "unreadable_result")
    }
    switch outcome {
    case let .formatted(formatted):
        return FormattedError(text: formatted.text, hint: formatted.hasHint ? formatted.hint : nil)
    case let .refusedRule(rule):
        throw FormatErrorOptionError(rule: rule)
    }
}
"#;

/// `Errors.swift`: the template and one code enum per `#[error]` type.
fn errors_swift(model: &Model, module: &str, error: &str) -> String {
    let mut out = String::from(HEADER);
    let _ = write!(
        out,
        "import Foundation\nimport {module}FFI\nimport SwiftProtobuf\n"
    );
    out.push_str(
        &ERRORS_SWIFT
            .replace("@ERROR@", error)
            .replace("@FFI@", &format!("{module}FFI")),
    );
    for declared in &model.errors {
        let _ = write!(
            out,
            "\n/// The codes `{}` carries.\npublic enum {}Code: String, Sendable {{\n",
            declared.name, declared.name
        );
        for variant in &declared.variants {
            let _ = writeln!(
                out,
                "    case {} = \"{}\"",
                swift_ident(&typescript_name(&variant.code)),
                variant.code
            );
        }
        out.push_str("}\n");
    }
    out
}

/// What a list, batch or stream hands the caller, and how the bytes the native
/// layer delivers become it. `@ERROR@` and `@FFI@` are replaced.
const PAGES_SWIFT: &str = r#"
/// One page of a list: its items, the revision they were read at and whether another page follows.
public struct Page<Item: Sendable>: Sendable {
    public let items: [Item]
    public let revision: String
    public let fromCache: Bool
    public let hasNext: Bool
    public let total: Total?
}

/// The size of a list, as the server states it.
public struct Total: Sendable {
    public enum Kind: Sendable {
        case estimate
        case exact
    }

    public let value: UInt64
    public let kind: Kind
}

/// One result of a batch chunk, in request order.
public enum BatchItem<Item: Sendable>: Sendable {
    case ok(Item)
    case failed(@ERROR@)
}

func decodePage<Item: SwiftProtobuf.Message & Sendable>(_ bytes: Data, as type: Item.Type) throws -> Page<Item> {
    let page = try Bones_Sdk_V1_Page(serializedBytes: bytes)
    let total: Total? = page.hasTotal ? Total(value: page.total.value, kind: page.total.kind == .exact ? .exact : .estimate) : nil
    return Page(
        items: try page.items.map { try Item(serializedBytes: $0) },
        revision: page.revision,
        fromCache: page.fromCache,
        hasNext: page.hasNext,
        total: total
    )
}

func decodeBatchChunk<Item: SwiftProtobuf.Message & Sendable>(_ bytes: Data, as type: Item.Type) throws -> [BatchItem<Item>] {
    try Bones_Sdk_V1_BatchChunk(serializedBytes: bytes).results.map { result -> BatchItem<Item> in
        switch result.outcome {
        case let .item(item):
            return .ok(try Item(serializedBytes: item))
        case let .error(error):
            return .failed(@ERROR@.call(error, bytes: try error.serializedData()))
        case nil:
            var missing = Bones_Sdk_V1_CallError()
            missing.code = "PRECONDITION_FAILED"
            missing.emitter = "bones"
            missing.platform = "PRECONDITION_FAILED"
            missing.connectCode = "failed_precondition"
            missing.message = "the batch outcome named neither an item nor an error"
            return .failed(@ERROR@.call(missing, bytes: try missing.serializedData()))
        }
    }
}

/// A stream of what `decode` reads of each message the handle `open` opens delivers. A failure ends it with the call error; ending it cancels the handle.
func streamOf<Output: Sendable>(
    open: @escaping @Sendable () async throws -> FfiHandle,
    decode: @escaping @Sendable (Data) throws -> Output
) -> AsyncThrowingStream<Output, Error> {
    AsyncThrowingStream { continuation in
        let task = Task {
            do {
                let handle = try await open()
                try await withTaskCancellationHandler {
                    while let bytes = try await handle.next() {
                        continuation.yield(try decode(bytes))
                    }
                } onCancel: {
                    handle.cancel()
                }
                continuation.finish()
            } catch {
                continuation.finish(throwing: @ERROR@.mapped(error))
            }
        }
        continuation.onTermination = { _ in
            task.cancel()
        }
    }
}
"#;

fn pages_swift(module: &str, error: &str) -> String {
    let mut out = String::from(HEADER);
    let _ = write!(
        out,
        "import Foundation\nimport {module}FFI\nimport SwiftProtobuf\n"
    );
    out.push_str(&PAGES_SWIFT.replace("@ERROR@", error));
    out
}

