//! `wrapper swift`: the Swift package that fronts the uniffi build of a Layer 2
//! crate.
//!
//! Every file is generated from the crate's `#[error]` and `#[client]` items,
//! the SPEC's `l2_methods` and the descriptor set that declares the messages
//! the exports cross as. The package holds no decision logic: a method builds
//! the protobuf message of its arguments, calls the uniffi function with the
//! bytes and decodes the bytes it answers, once, with SwiftProtobuf. The
//! uniffi bindgen output is copied into the package as it is; the package
//! never reinvents the FFI layer.
//!
//! The package takes no root, pin or verifier, and the server's address goes
//! only to the constructor of each client's FFI object.

