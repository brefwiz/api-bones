//! `wrapper kotlin`: the Kotlin package that fronts the native build of a
//! Layer 2 crate.
//!
//! Layer 1 is the uniffi-bindgen output of the crate's cdylib, copied
//! verbatim. Everything else is generated from the crate's `#[error]` and
//! `#[client]` items, the SPEC's `l2_methods` and the descriptor set that
//! declares the messages the exports cross as. The package holds no decision
//! logic: a method builds the protobuf message of its arguments, calls the
//! uniffi function with the bytes and decodes the bytes it answers once, with
//! the Java messages protoc generates. User-facing text comes from the core
//! (`formatError`), never from a diagnostic message. No symbol accepts a
//! trust root, pin or verifier: the only address is the entry's `baseUrl`.

