/// What the SPEC says about the one Kotlin package.
struct Package {
    /// The SPEC `service`.
    service: String,
    /// The Layer 2 crate.
    crate_name: String,
    /// The Kotlin package, as declared by the surfaces that list it.
    name: String,
    /// The `sdk_surfaces` and each endpoint's Rust methods.
    spec: SpecL2Methods,
    /// The surfaces whose kotlin targets list the package.
    listed: BTreeSet<String>,
}

/// The uniffi-bindgen output the package carries as its Layer 1.
struct Bindings {
    /// The Kotlin package the bindgen output declares.
    package: String,
    /// Every file of the output: its path under the output root and its text.
    files: Vec<File>,
}

/// Writes the Kotlin package described by `args`.
///
/// # Errors
///
/// A SPEC that declares no Kotlin package or more than one, a crate or
/// descriptor set that cannot be read, a bindgen output that is empty or
/// declares no `FfiHandle`, an export the contract cannot spell, and an I/O
/// error.
pub(crate) fn run(args: &crate::WrapperArgs) -> anyhow::Result<()> {
    let package = package_of(&args.spec, &args.krate)?;
    let model = crate::features::read_model(&args.krate)?;
    let contract = Contract::read(&args.descriptor)?;
    let bindings = Bindings::read(&args.bindings)?;
    let files = generate(&model, &package, &contract, &bindings)?;
    write(&args.out, &files)
}

fn write(out: &Path, files: &[File]) -> anyhow::Result<()> {
    for (path, text) in files {
        let target = out.join(path);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&target, text)
            .with_context(|| format!("cannot write {}", target.display()))?;
    }
    Ok(())
}

/// The one Kotlin package of the SPEC.
///
/// # Errors
///
/// A SPEC without front matter, service or surfaces; no surface that declares
/// a kotlin package, or surfaces that declare several (one package per
/// language); a package that is not a lower-case dotted name; a manifest that
/// names no crate.
fn package_of(spec: &Path, krate: &Path) -> anyhow::Result<Package> {
    let text =
        std::fs::read_to_string(spec).with_context(|| format!("cannot read {}", spec.display()))?;
    let front = text
        .strip_prefix("---\n")
        .and_then(|rest| rest.split("\n---").next())
        .ok_or_else(|| anyhow!("{} has no front matter", spec.display()))?;
    let document: serde_yaml::Value = serde_yaml::from_str(front)?;
    let service = document["service"]
        .as_str()
        .ok_or_else(|| anyhow!("the SPEC names no service"))?
        .to_owned();
    let surfaces = document["sdk_surfaces"]
        .as_mapping()
        .ok_or_else(|| anyhow!("the SPEC lists no sdk_surfaces"))?;
    let mut declared = BTreeSet::new();
    for (_, entry) in surfaces {
        declared.extend(kotlin_packages(entry));
    }
    let mut names = declared.into_iter();
    let name = names
        .next()
        .ok_or_else(|| anyhow!("no sdk_surfaces entry declares a kotlin target package"))?;
    let others: Vec<String> = names.collect();
    ensure!(
        others.is_empty(),
        "the SPEC declares {} kotlin packages (`{name}`, `{}`): a wrapper is one package per language",
        others.len() + 1,
        others.join("`, `")
    );
    ensure!(
        name.split('.').all(|segment| {
            segment.starts_with(|c: char| c.is_ascii_lowercase())
                && segment
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                && !KEYWORDS.contains(&segment)
        }),
        "kotlin package `{name}` is not a lower-case dotted name"
    );
    let mut spec_l2 = SpecL2Methods::default();
    let mut listed = BTreeSet::new();
    for (id, entry) in surfaces {
        let id = id.as_str().unwrap_or_default().to_owned();
        spec_l2.surfaces.insert(id.clone());
        if !kotlin_packages(entry).contains(&name) {
            continue;
        }
        let by_endpoint = spec_l2.endpoints.entry(id.clone()).or_default();
        for (endpoint, languages) in entry["l2_methods"].as_mapping().into_iter().flatten() {
            let rust = by_endpoint
                .entry(endpoint.as_str().unwrap_or_default().to_owned())
                .or_default();
            for method in languages["rust"]
                .as_sequence()
                .into_iter()
                .flatten()
                .filter_map(|m| m.as_str())
            {
                if !rust.iter().any(|known| known == method) {
                    rust.push(method.to_owned());
                }
            }
        }
        listed.insert(id);
    }
    Ok(Package {
        service,
        crate_name: crate_name(krate)?,
        name,
        spec: spec_l2,
        listed,
    })
}

/// The packages one `sdk_surfaces` entry lists for its kotlin target.
fn kotlin_packages(entry: &serde_yaml::Value) -> BTreeSet<String> {
    entry["targets"]["kotlin"]["packages"]
        .as_sequence()
        .into_iter()
        .flatten()
        .filter_map(|package| package.as_str().map(str::to_owned))
        .collect()
}

/// The `name` of the `[package]` table of the manifest in `krate`.
fn crate_name(krate: &Path) -> anyhow::Result<String> {
    let path = krate.join("Cargo.toml");
    let text = std::fs::read_to_string(&path)
        .with_context(|| format!("cannot read {}", path.display()))?;
    text.lines()
        .skip_while(|line| line.trim() != "[package]")
        .skip(1)
        .take_while(|line| !line.trim_start().starts_with('['))
        .find_map(|line| {
            let value = line.strip_prefix("name")?.trim_start().strip_prefix('=')?;
            Some(value.trim().trim_matches('"').to_owned())
        })
        .ok_or_else(|| anyhow!("{} names no crate", path.display()))
}

impl Bindings {
    /// The output tree at `root`.
    ///
    /// # Errors
    ///
    /// A root that is missing or holds no file, and an output with no Kotlin
    /// file that declares `FfiHandle`.
    fn read(root: &Path) -> anyhow::Result<Self> {
        let mut paths = Vec::new();
        collect(root, &mut paths)?;
        ensure!(
            !paths.is_empty(),
            "the bindings directory {} holds no file",
            root.display()
        );
        paths.sort();
        let mut files = Vec::new();
        for path in paths {
            let text = std::fs::read_to_string(&path)
                .with_context(|| format!("cannot read {}", path.display()))?;
            let relative = path.strip_prefix(root).expect("under the root");
            files.push((relative.to_string_lossy().replace('\\', "/"), text));
        }
        let package = files
            .iter()
            .filter(|(path, text)| path.ends_with(".kt") && text.contains("FfiHandle"))
            .find_map(|(_, text)| {
                text.lines()
                    .find_map(|line| line.strip_prefix("package "))
                    .map(|name| name.trim().to_owned())
            })
            .ok_or_else(|| {
                anyhow!(
                    "the bindings in {} declare no FfiHandle in a Kotlin package",
                    root.display()
                )
            })?;
        Ok(Self { package, files })
    }
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> anyhow::Result<()> {
    let entries =
        std::fs::read_dir(dir).with_context(|| format!("cannot read {}", dir.display()))?;
    for entry in entries {
        let path = entry?.path();
        if path.is_dir() {
            collect(&path, out)?;
        } else {
            out.push(path);
        }
    }
    Ok(())
}

/// The file descriptor set that declares every message the exports cross as.
struct Contract {
    pool: DescriptorPool,
}

impl Contract {
    fn read(path: &Path) -> anyhow::Result<Self> {
        let bytes = std::fs::read(path)
            .with_context(|| format!("cannot read the descriptor set {}", path.display()))?;
        let pool = DescriptorPool::decode(bytes.as_slice())
            .with_context(|| format!("invalid descriptor set {}", path.display()))?;
        ensure!(
            pool.files().next().is_some(),
            "the descriptor set {} is empty",
            path.display()
        );
        Ok(Self { pool })
    }

    fn message(&self, full_name: &str) -> anyhow::Result<MessageDescriptor> {
        self.pool
            .get_message_by_name(full_name)
            .or_else(|| DescriptorPool::global().get_message_by_name(full_name))
            .ok_or_else(|| anyhow!("message `{full_name}` is missing from the descriptor set"))
    }
}

/// The name protoc gives the Java outer class of a file: its stem in camel
/// case.
fn camel(stem: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for c in stem.chars() {
        if c == '_' {
            upper = true;
        } else if c.is_ascii_digit() {
            out.push(c);
            upper = true;
        } else if upper {
            out.push(c.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// The Java class protoc writes for the type `full_name` of `file`.
fn java_name(file: &FileDescriptor, full_name: &str) -> String {
    let proto_package = file.package_name();
    let local = full_name
        .strip_prefix(proto_package)
        .and_then(|rest| rest.strip_prefix('.'))
        .unwrap_or(full_name);
    let options = file.file_descriptor_proto().options.as_ref();
    let package = options
        .and_then(|o| o.java_package.as_deref())
        .filter(|p| !p.is_empty())
        .unwrap_or(proto_package);
    let mut parts = Vec::new();
    if !package.is_empty() {
        parts.push(package.to_owned());
    }
    if !options.and_then(|o| o.java_multiple_files).unwrap_or(false) {
        parts.push(outer_class(file));
    }
    parts.push(local.to_owned());
    parts.join(".")
}

fn outer_class(file: &FileDescriptor) -> String {
    if let Some(name) = file
        .file_descriptor_proto()
        .options
        .as_ref()
        .and_then(|o| o.java_outer_classname.as_deref())
        .filter(|name| !name.is_empty())
    {
        return name.to_owned();
    }
    let base = file.name().rsplit('/').next().unwrap_or_default();
    let name = camel(base.strip_suffix(".proto").unwrap_or(base));
    let taken = file.messages().any(|m| m.name() == name)
        || file.enums().any(|e| e.name() == name)
        || file.services().any(|s| s.name() == name);
    if taken {
        format!("{name}OuterClass")
    } else {
        name
    }
}

fn message_class(message: &MessageDescriptor) -> String {
    java_name(&message.parent_file(), message.full_name())
}

fn enum_class(descriptor: &EnumDescriptor) -> String {
    java_name(&descriptor.parent_file(), descriptor.full_name())
}

/// How a Kotlin value becomes the Java value the builder takes.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Conv {
    Same,
    UInt,
    ULong,
    Bytes,
}

impl Conv {
    fn to_java(self, value: &str) -> String {
        match self {
            Self::Same => value.to_owned(),
            Self::UInt => format!("{value}.toInt()"),
            Self::ULong => format!("{value}.toLong()"),
            Self::Bytes => format!("com.google.protobuf.ByteString.copyFrom({value})"),
        }
    }
}

/// The Kotlin type of a field and how it reaches the Java builder.
fn kotlin_type(kind: &Kind) -> (String, Conv) {
    let (ty, conv) = match kind {
        Kind::Double => ("Double", Conv::Same),
        Kind::Float => ("Float", Conv::Same),
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 => ("Int", Conv::Same),
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 => ("Long", Conv::Same),
        Kind::Uint32 | Kind::Fixed32 => ("UInt", Conv::UInt),
        Kind::Uint64 | Kind::Fixed64 => ("ULong", Conv::ULong),
        Kind::Bool => ("Boolean", Conv::Same),
        Kind::String => ("String", Conv::Same),
        Kind::Bytes => ("ByteArray", Conv::Bytes),
        Kind::Message(message) => return (message_class(message), Conv::Same),
        Kind::Enum(descriptor) => return (enum_class(descriptor), Conv::Same),
    };
    (ty.to_owned(), conv)
}

/// One parameter of a method, bound to the field of the args message it
/// travels in.
struct Arg {
    name: String,
    ty: String,
    conv: Conv,
    optional: bool,
    list: bool,
    /// The Java builder member's suffix: `Id` of `setId`.
    member: String,
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_uppercase().chain(chars).collect())
        .unwrap_or_default()
}

fn lower_first(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_lowercase().chain(chars).collect())
        .unwrap_or_default()
}

/// `Svc` of the service `svc`, as a type-name prefix.
fn service_pascal(service: &str) -> String {
    service
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(pascal)
        .collect()
}

/// A name the generated Kotlin can spell as written.
fn ident(name: String) -> anyhow::Result<String> {
    ensure!(
        !KEYWORDS.contains(&name.as_str()) && !RESERVED.contains(&name.as_str()),
        "`{name}` is a Kotlin keyword or a name the generated bodies own"
    );
    Ok(name)
}

fn arg_of(field: &FieldDescriptor) -> anyhow::Result<Arg> {
    ensure!(
        !field.is_map(),
        "field `{}` is a map, which a method parameter cannot be",
        field.name()
    );
    let (ty, conv) = kotlin_type(&field.kind());
    let name = ident(field.json_name().to_owned())?;
    Ok(Arg {
        member: pascal(&name),
        name,
        ty,
        conv,
        optional: field
            .field_descriptor_proto()
            .proto3_optional
            .unwrap_or(false),
        list: field.is_list(),
    })
}

/// The parameters of `export` bound to the fields of the message its args
/// cross as, in parameter order.
///
/// # Errors
///
/// An args message the descriptor set lacks, one whose field names are not
/// exactly the parameter names, a zero-parameter export whose args are not
/// `google.protobuf.Empty`, and a parameter that cannot be spelled.
fn args_of(contract: &Contract, export: &Export) -> anyhow::Result<Vec<Arg>> {
    let args = export.args.full_name();
    let at = || format!("`{}` (args `{args}`)", export.method);
    if export.params.is_empty() {
        ensure!(
            export.args == Wire::Empty,
            "{} takes no parameter, so its args are `google.protobuf.Empty`",
            at()
        );
        return Ok(Vec::new());
    }
    let message = contract.message(args)?;
    let wanted: BTreeSet<String> = export.params.iter().map(|p| p.json_name()).collect();
    let declared: BTreeSet<String> = message.fields().map(|f| f.json_name().to_owned()).collect();
    ensure!(
        wanted == declared,
        "{}: the message declares fields {declared:?} but the parameters are {wanted:?}",
        at()
    );
    export
        .params
        .iter()
        .map(|param| {
            let name = param.json_name();
            let field = message
                .fields()
                .find(|f| f.json_name() == name)
                .ok_or_else(|| anyhow!("{}: no field `{name}`", at()))?;
            arg_of(&field).with_context(at)
        })
        .collect()
}

/// The Kotlin type and expression that read a value of `wire` out of the
/// bytes `bytes`; `None` for no value.
fn decoded(
    contract: &Contract,
    wire: &Wire,
    bytes: &str,
) -> anyhow::Result<Option<(String, String)>> {
    let class = match wire {
        Wire::Empty => return Ok(None),
        Wire::Wrapper(wrapper) => wkt_class(*wrapper),
        Wire::Message(reference) => message_class(&contract.message(&reference.full_name)?),
    };
    let read = format!("{class}.parseFrom({bytes})");
    Ok(Some(match wire {
        Wire::Wrapper(Wrapper::Bool) => ("Boolean".to_owned(), format!("{read}.value")),
        Wire::Wrapper(Wrapper::Int32) => ("Int".to_owned(), format!("{read}.value")),
        Wire::Wrapper(Wrapper::UInt32) => ("UInt".to_owned(), format!("{read}.value.toUInt()")),
        Wire::Wrapper(Wrapper::Int64) => ("Long".to_owned(), format!("{read}.value")),
        Wire::Wrapper(Wrapper::UInt64) => ("ULong".to_owned(), format!("{read}.value.toULong()")),
        Wire::Wrapper(Wrapper::Double) => ("Double".to_owned(), format!("{read}.value")),
        Wire::Wrapper(Wrapper::String) => ("String".to_owned(), format!("{read}.value")),
        Wire::Wrapper(Wrapper::Bytes) => (
            "ByteArray".to_owned(),
            format!("{read}.value.toByteArray()"),
        ),
        _ => (class, read),
    }))
}

/// The Java class of a `google.protobuf` wrapper message.
fn wkt_class(wrapper: Wrapper) -> String {
    let name = wrapper.full_name();
    format!("com.{name}")
}

/// One method of a generated client, as a class member indented four spaces.
struct Method {
    text: String,
    /// Declared `suspend`.
    suspend: bool,
    signature: String,
}

/// The list and batch shapes yield generated messages.
fn item_class(contract: &Contract, item: &Wire, at: &str) -> anyhow::Result<String> {
    match item {
        Wire::Message(reference) => Ok(message_class(&contract.message(&reference.full_name)?)),
        other => Err(anyhow!(
            "{at}: a list or batch yields a generated message, not `{}`",
            other.full_name()
        )),
    }
}

/// The lines that build the `request` bytes of a call.
fn request_kt(contract: &Contract, export: &Export, args: &[Arg]) -> anyhow::Result<String> {
    if args.is_empty() {
        return Ok(
            "        val request = com.google.protobuf.Empty.getDefaultInstance().toByteArray()\n"
                .to_owned(),
        );
    }
    let class = message_class(&contract.message(export.args.full_name())?);
    let mut text = format!("        val builder = {class}.newBuilder()\n");
    for arg in args {
        let name = &arg.name;
        let member = &arg.member;
        if arg.list {
            let value = if arg.conv == Conv::Same {
                name.clone()
            } else {
                format!("{name}.map {{ {} }}", arg.conv.to_java("it"))
            };
            let _ = writeln!(text, "        builder.addAll{member}({value})");
        } else if arg.optional {
            let _ = writeln!(
                text,
                "        if ({name} != null) builder.set{member}({})",
                arg.conv.to_java(name)
            );
        } else {
            let _ = writeln!(
                text,
                "        builder.set{member}({})",
                arg.conv.to_java(name)
            );
        }
    }
    text.push_str("        val request = builder.build().toByteArray()\n");
    Ok(text)
}

const GUARD: &str =
    "        } catch (e: FfiException) {\n            throw e.toError()\n        }\n";

/// The Kotlin member for `export`. `imports` collects the uniffi functions it
/// calls.
fn method_kt(
    contract: &Contract,
    package: &Package,
    client: &Client,
    export: &Export,
    imports: &mut BTreeSet<String>,
) -> anyhow::Result<Method> {
    let at = format!("`{}`", export.method);
    let name = ident(typescript_name(&export.method))?;
    let args = args_of(contract, export)?;
    let function = typescript_name(&export_name(&package.service, &client.ty, &export.method)?);
    imports.insert(function.clone());
    let call = if export.shape == Shape::Method {
        format!("{function}(ffi, request)")
    } else {
        format!("{function}(request)")
    };
    let mut params: Vec<String> = args
        .iter()
        .filter(|arg| !arg.optional)
        .map(|arg| {
            if arg.list {
                format!("{}: List<{}>", arg.name, arg.ty)
            } else {
                format!("{}: {}", arg.name, arg.ty)
            }
        })
        .collect();
    params.extend(
        args.iter()
            .filter(|arg| arg.optional)
            .map(|arg| format!("{}: {}? = null", arg.name, arg.ty)),
    );
    let params = params.join(", ");
    let request = request_kt(contract, export, &args)?;
    let (suspend, ret, body) = match &export.ret {
        Return::Handle { kind, item } => {
            let (flow, shape) = match kind {
                HandleKind::List => {
                    let class = item_class(contract, item, &at)?;
                    (
                        format!("Flow<Page<{class}>>"),
                        format!("pagesOf({{ {call} }}, {{ {class}.parseFrom(it) }})"),
                    )
                }
                HandleKind::Batch => {
                    let class = item_class(contract, item, &at)?;
                    (
                        format!("Flow<List<BatchItem<{class}>>>"),
                        format!("batchesOf({{ {call} }}, {{ {class}.parseFrom(it) }})"),
                    )
                }
                HandleKind::Stream => {
                    let (ty, read) = decoded(contract, item, "it")?
                        .ok_or_else(|| anyhow!("{at}: a stream yields a value"))?;
                    (
                        format!("Flow<{ty}>"),
                        format!("itemsOf({{ {call} }}, {{ {read} }})"),
                    )
                }
            };
            (
                false,
                format!(": {flow}"),
                format!("{request}        return {shape}\n"),
            )
        }
        Return::Result { ok, .. } if !export.sync => call_kt(contract, ok, &call, &request, true)?,
        Return::Value(wire) | Return::Result { ok: wire, .. } => {
            call_kt(contract, wire, &call, &request, false)?
        }
        Return::Unit => (
            false,
            String::new(),
            format!("{request}        try {{\n            {call}\n{GUARD}"),
        ),
    };
    let lead = if suspend { "suspend fun" } else { "fun" };
    Ok(Method {
        text: format!("    {lead} {name}({params}){ret} {{\n{body}    }}\n"),
        suspend,
        signature: format!("{lead} {name}({params}){ret}"),
    })
}

/// The suspension, return type and body of a call that answers one value.
fn call_kt(
    contract: &Contract,
    wire: &Wire,
    call: &str,
    request: &str,
    suspend: bool,
) -> anyhow::Result<(bool, String, String)> {
    Ok(match decoded(contract, wire, call)? {
        Some((ty, read)) => (
            suspend,
            format!(": {ty}"),
            format!("{request}        try {{\n            return {read}\n{GUARD}"),
        ),
        None => (
            suspend,
            String::new(),
            format!("{request}        try {{\n            {call}\n{GUARD}"),
        ),
    })
}

/// The package directory: `com.a.b` is `com/a/b`.
fn directory(package: &str) -> String {
    package.replace('.', "/")
}

/// Every file of the package, in path order.
///
/// # Errors
///
/// A name that cannot be spelled, an export of a surface the package is not a
/// target of, an export `l2_methods` does not list, and a message the
/// descriptor set lacks or declares other than the export's parameters.
fn generate(
    model: &Model,
    package: &Package,
    contract: &Contract,
    bindings: &Bindings,
) -> anyhow::Result<Vec<File>> {
    for client in &model.clients {
        for export in &client.exports {
            ensure!(
                package.listed.contains(&export.surface),
                "package `{}` is not a kotlin target of surface `{}`, which the exports of `{}` name",
                package.name,
                export.surface,
                package.crate_name
            );
        }
    }
    let document = l2_methods(
        model,
        &package.spec,
        &package.service,
        &package.crate_name,
        &package.name,
    )?;
    let service = service_pascal(&package.service);
    let root = format!("{SOURCE_ROOT}/{}", directory(&package.name));
    let mut imports = BTreeSet::new();
    let mut classes = String::new();
    let mut statics = String::new();
    let mut surface = String::new();
    let mut properties = Vec::new();
    for client in &model.clients {
        let mut members = Vec::new();
        let mut signatures = Vec::new();
        for export in &client.exports {
            let method = method_kt(contract, package, client, export, &mut imports)?;
            if export.shape == Shape::Method {
                members.push(method.text);
                signatures.push(format!("    {}\n", method.signature));
            } else {
                let dedented: String = method
                    .text
                    .lines()
                    .map(|line| format!("{}\n", line.strip_prefix("    ").unwrap_or(line)))
                    .collect();
                let _ = write!(statics, "\n{dedented}");
                let _ = writeln!(surface, "{}", method.signature);
            }
        }
        if client.module || members.is_empty() {
            continue;
        }
        let _ = write!(
            classes,
            "\nclass {} internal constructor(private val ffi: {service}Ffi) {{\n{}}}\n",
            client.ty,
            members.join("\n")
        );
        let _ = write!(
            surface,
            "class {} {{\n{}}}\n",
            client.ty,
            signatures.concat()
        );
        properties.push((lower_first(&client.ty), client.ty.clone()));
    }
    let mut entry = format!(
        "\n/** Every client of the service, opened from one host. */\nclass {service}Sdk(baseUrl: String, host: FfiHost) {{\n    private val ffi = {service}Ffi(baseUrl, host)\n"
    );
    if !properties.is_empty() {
        entry.push('\n');
    }
    for (property, ty) in &properties {
        let _ = writeln!(entry, "    val {property}: {ty} = {ty}(ffi)");
    }
    entry.push_str("}\n");
    let mut client = format!("{HEADER}package {}\n\n", package.name);
    let mut uniffi: BTreeSet<String> = imports;
    uniffi.extend(
        [
            format!("{service}Ffi"),
            "FfiException".to_owned(),
            "FfiHandle".to_owned(),
            "FfiHost".to_owned(),
        ]
        .into_iter(),
    );
    uniffi.remove("FfiHandle");
    for name in &uniffi {
        let _ = writeln!(client, "import {}.{name}", bindings.package);
    }
    client.push_str("import kotlinx.coroutines.flow.Flow\n");
    client.push_str(&entry);
    client.push_str(&classes);
    client.push_str(&statics);
    let mut files: Vec<File> = vec![
        ("build.gradle.kts".to_owned(), build_gradle(package)),
        ("buf.gen.yaml".to_owned(), buf_gen()),
        ("l2-methods.json".to_owned(), document.to_json()),
        (SURFACE_FILE.to_owned(), surface),
        (format!("{root}/{service}Client.kt"), client),
        (
            format!("{root}/Errors.kt"),
            errors_kt(model, package, &service, bindings),
        ),
        (format!("{root}/Pages.kt"), pages_kt(package, bindings)),
    ];
    for (path, text) in &bindings.files {
        files.push((format!("{root}/ffi/{path}"), text.clone()));
    }
    files.sort();
    Ok(files)
}

fn build_gradle(package: &Package) -> String {
    format!(
        "{HEADER}plugins {{\n    kotlin(\"jvm\") version \"{KOTLIN_PLUGIN}\"\n}}\n\ngroup = \"{}\"\nversion = \"{WRAPPER_PLACEHOLDER_VERSION}\"\n\nrepositories {{\n    mavenCentral()\n}}\n\ndependencies {{\n    api(\"{PROTOBUF_KOTLIN}\")\n    api(\"{COROUTINES}\")\n    implementation(\"{JNA}\")\n}}\n\nkotlin {{\n    jvmToolchain(21)\n}}\n",
        package.name
    )
}

/// The protoc plugins that write the messages the package names: the Java
/// classes the generated code builds and parses, and the Kotlin DSL beside
/// them. Running them is the consumer's build step.
fn buf_gen() -> String {
    format!(
        "# SPDX-License-Identifier: MIT\n# Generated by api-bones-sdk-gen; do not edit.\nversion: v2\nplugins:\n  - protoc_builtin: java\n    out: src/main/java\n  - protoc_builtin: kotlin\n    out: {SOURCE_ROOT}\n"
    )
}

fn errors_kt(model: &Model, package: &Package, service: &str, bindings: &Bindings) -> String {
    let mut out = format!(
        "{HEADER}package {}\n\nimport {}.FfiException\nimport {}.formatError as ffiFormatError\n",
        package.name, bindings.package, bindings.package
    );
    let _ = write!(
        out,
        "\n/**\n * A failed call: the core's error, decoded once. The exception text is the\n * error code; the diagnostic message is for logs and is never shown to a person.\n */\nsealed class {service}Error(val call: bones.sdk.v1.Boundary.CallError) : Exception(call.code) {{\n    /** A call that failed. */\n    class Call(call: bones.sdk.v1.Boundary.CallError) : {service}Error(call)\n\n    /** A list that failed after it had delivered pages; `call.page` says how many. */\n    class ListFailed(call: bones.sdk.v1.Boundary.CallError) : {service}Error(call)\n}}\n"
    );
    let _ = write!(
        out,
        "\ninternal fun FfiException.toError(): {service}Error {{\n    val call = bones.sdk.v1.Boundary.CallError.parseFrom(callBytes())\n    return if (call.hasPage()) {service}Error.ListFailed(call) else {service}Error.Call(call)\n}}\n\nprivate fun FfiException.callBytes(): ByteArray = when (this) {{\n    is FfiException.Call -> bytes\n}}\n"
    );
    for error in &model.errors {
        let _ = write!(
            out,
            "\n/** The codes `{}` carries. */\nobject {}Codes {{\n",
            error.name, error.name
        );
        for variant in &error.variants {
            let _ = writeln!(
                out,
                "    const val {}: String = \"{}\"",
                variant.code, variant.code
            );
        }
        out.push_str("}\n");
    }
    out.push_str(
        "\n/** An error rendered for a person, in the locale and time zone asked for. */\ndata class FormattedError(val text: String, val hint: String?)\n\n/** The core refused a formatting option, such as an unknown time zone. */\nclass FormatErrorOptionException(val rule: String) : Exception(rule)\n\n/**\n * The text of `error` for a person, rendered by the core in `locale`.\n * `timeZone` defaults to UTC.\n *\n * @throws FormatErrorOptionException when the core refuses `timeZone`.\n */\nfun formatError(error: ",
    );
    let _ = write!(
        out,
        "{service}Error, locale: String, timeZone: String? = null): FormattedError {{\n    val result = bones.sdk.v1.Boundary.FormatResult.parseFrom(\n        ffiFormatError(error.call.toByteArray(), locale, timeZone),\n    )\n    if (result.hasRefusedRule()) throw FormatErrorOptionException(result.refusedRule)\n    val formatted = result.formatted\n    return FormattedError(formatted.text, if (formatted.hasHint()) formatted.hint else null)\n}}\n"
    );
    out
}

fn pages_kt(package: &Package, bindings: &Bindings) -> String {
    format!(
        "{HEADER}package {}\n\nimport {}.FfiException\nimport {}.FfiHandle\nimport kotlinx.coroutines.flow.Flow\nimport kotlinx.coroutines.flow.flow\n{PAGES_BODY}",
        package.name, bindings.package, bindings.package
    )
}

const PAGES_BODY: &str = r#"
/** One page of a list. */
data class Page<T>(
    val items: List<T>,
    val revision: String,
    val fromCache: Boolean,
    val hasNext: Boolean,
    val total: bones.v1.Pagination.Total?,
)

/** The outcome of one requested id of a batch. */
sealed class BatchItem<out T> {
    class Found<T>(val item: T) : BatchItem<T>()

    class Failed(val call: bones.sdk.v1.Boundary.CallError) : BatchItem<Nothing>()
}

/** Runs a native call; a failure leaves as the typed error of the service. */
private suspend fun <T> mapped(block: suspend () -> T): T =
    try {
        block()
    } catch (e: FfiException) {
        throw e.toError()
    }

/** The deliveries of a handle, read until it ends; the handle is released when the flow ends or is cancelled. */
private fun <R> deliveries(open: suspend () -> FfiHandle, decode: (ByteArray) -> R): Flow<R> = flow {
    val handle = mapped { open() }
    try {
        while (true) {
            val bytes = mapped { handle.next() } ?: break
            emit(decode(bytes))
        }
    } finally {
        handle.cancel()
        handle.close()
    }
}

internal fun <T> pagesOf(open: suspend () -> FfiHandle, decode: (ByteArray) -> T): Flow<Page<T>> =
    deliveries(open) { bytes ->
        val page = bones.sdk.v1.Boundary.Page.parseFrom(bytes)
        Page(
            items = page.itemsList.map { decode(it.toByteArray()) },
            revision = page.revision,
            fromCache = page.fromCache,
            hasNext = page.hasNext,
            total = if (page.hasTotal()) page.total else null,
        )
    }

internal fun <T> itemsOf(open: suspend () -> FfiHandle, decode: (ByteArray) -> T): Flow<T> =
    deliveries(open, decode)

internal fun <T> batchesOf(
    open: suspend () -> FfiHandle,
    decode: (ByteArray) -> T,
): Flow<List<BatchItem<T>>> =
    deliveries(open) { bytes ->
        bones.sdk.v1.Boundary.BatchChunk.parseFrom(bytes).resultsList.map { result ->
            if (result.hasItem()) {
                BatchItem.Found(decode(result.item.toByteArray()))
            } else {
                BatchItem.Failed(result.error)
            }
        }
    }
"#;

