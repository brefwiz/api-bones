#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Generates the api-bones-types package's sources from its Rust crate:
//   1. `cargo run -p api-bones-schema-gen` writes the combined JSON Schema to
//      schema/api-bones.json;
//   2. json-schema-to-typescript turns it into src/generated/api-bones.ts.
// Both outputs are gitignored.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = join(repoRoot, "api-bones-types");
// The generator is a dependency of the package, not of the repository root, so
// it is resolved from the package directory.
const { compile } = createRequire(join(packageDir, "package.json"))("json-schema-to-typescript");
const schemaFile = join(packageDir, "schema", "api-bones.json");
const outFile = join(packageDir, "src", "generated", "api-bones.ts");

const banner = [
  "// AUTO-GENERATED FILE. DO NOT EDIT BY HAND.",
  "// Generated by scripts/generate-api-bones-types.mjs from the api-bones crate.",
  "",
  "",
].join("\n");

function writeSchema() {
  mkdirSync(dirname(schemaFile), { recursive: true });
  // Run from the repository root so its .cargo/config.toml, which declares the
  // brefwiz registry, is discovered.
  execFileSync("cargo", ["run", "--locked", "--quiet", "-p", "api-bones-schema-gen", "--", schemaFile], {
    stdio: "inherit",
    cwd: repoRoot,
  });
}

// Keywords that constrain the values a subschema accepts. A subschema with none
// of them accepts anything, which json-schema-to-typescript would otherwise
// render as an object with an index signature.
const CONSTRAINING_KEYWORDS = new Set([
  "type", "$ref", "enum", "const", "properties", "patternProperties", "additionalProperties",
  "items", "prefixItems", "anyOf", "oneOf", "allOf", "not", "if", "required", "format",
  "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
  "minLength", "maxLength", "pattern", "minItems", "maxItems", "uniqueItems", "contains",
  "minProperties", "maxProperties", "propertyNames", "dependencies",
]);

function acceptsAnyValue(subschema) {
  return Object.keys(subschema).every((key) => !CONSTRAINING_KEYWORDS.has(key));
}

// Returns the subschema to use in place of `subschema`, visiting only schema
// positions: `properties` values, `items`, `additionalProperties` and the
// `anyOf`/`oneOf`/`allOf` members.
function typeAnyValue(subschema) {
  if (subschema === true) return { tsType: "unknown" };
  if (subschema === null || typeof subschema !== "object" || Array.isArray(subschema)) return subschema;
  if (acceptsAnyValue(subschema)) return { ...subschema, tsType: "unknown" };
  for (const key of ["anyOf", "oneOf", "allOf"]) {
    if (Array.isArray(subschema[key])) subschema[key] = subschema[key].map(typeAnyValue);
  }
  if (subschema.properties) {
    for (const [name, child] of Object.entries(subschema.properties)) {
      subschema.properties[name] = typeAnyValue(child);
    }
  }
  if (Array.isArray(subschema.items)) subschema.items = subschema.items.map(typeAnyValue);
  else if (subschema.items !== undefined) subschema.items = typeAnyValue(subschema.items);
  if (subschema.additionalProperties !== undefined && subschema.additionalProperties !== false) {
    subschema.additionalProperties = typeAnyValue(subschema.additionalProperties);
  }
  return subschema;
}

// The definitions map and the root stay as they are: only what each definition
// contains is rewritten, on a copy, so schema/api-bones.json is untouched.
function withUnknownPayloads(schema) {
  const copy = structuredClone(schema);
  for (const [name, definition] of Object.entries(copy.definitions)) {
    copy.definitions[name] = typeAnyValue(definition);
  }
  return copy;
}

async function compileSchema() {
  const schema = withUnknownPayloads(JSON.parse(readFileSync(schemaFile, "utf8")));
  const source = await compile(schema, "ApiBones", {
    bannerComment: "",
    additionalProperties: false,
    style: { singleQuote: false, semi: true },
    declareExternallyReferenced: true,
    strictIndexSignatures: true,
    unknownAny: true,
  });
  // The root interface only makes every definition reachable for the
  // generator; no consumer imports it.
  return source.replace(/export interface ApiBones \{[\s\S]*?\n\}\n*/g, "").trim();
}

writeSchema();
const body = await compileSchema();
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${banner}${body}\n`);
console.log(`wrote ${schemaFile}`);
console.log(`wrote ${outFile}`);
