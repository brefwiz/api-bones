// Drives the shipped `embed-error-catalogs` bin as a consumer's `prebuild`
// does: a real process over real directories, asserting the files it writes.

import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

const bin = join(dirname(fileURLToPath(import.meta.url)), "..", "bin", "embed-error-catalogs.mjs");

let root: string;
let source: string;
let out: string;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "embed-error-catalogs-"));
  source = join(root, "catalogs");
  out = join(root, "generated");
  mkdirSync(source);
});

afterEach(() => rmSync(root, { recursive: true, force: true }));

function catalog(locale: string, entries: Record<string, string>): void {
  writeFileSync(join(source, `${locale}.json`), JSON.stringify(entries));
}

function run(...extra: string[]) {
  const args = extra.length
    ? extra
    : ["--source", source, "--out", out, "--spdx", "MIT", "--copyright", "Copyright (c) Acme."];
  return spawnSync(process.execPath, [bin, ...args], { encoding: "utf8" });
}

const EN = { "acme-origin.errors.DENIED.title": "Denied", "acme-edge.errors.GONE.title": "Gone" };
const FR = { "acme-origin.errors.DENIED.title": "Refuse", "acme-edge.errors.GONE.title": "Parti" };

describe("embed-error-catalogs", () => {
  it("emits one module per locale and skips provenance sidecars", () => {
    catalog("en", EN);
    catalog("fr", FR);
    writeFileSync(join(source, "fr.sources.json"), "{}");
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    expect(readdirSync(out).sort()).toEqual(["en.generated.ts", "fr.generated.ts", "loaders.generated.ts"]);
    expect(readFileSync(join(out, "fr.generated.ts"), "utf8")).toBe(
      `// SPDX-License-Identifier: MIT\n// Copyright (c) Acme.\n// Generated by embed-error-catalogs from ${source}. Do not edit.\n` +
        `const catalog: Readonly<Record<string, string>> = ${JSON.stringify(FR, null, 2)};\nexport default catalog;\n`,
    );
  });

  it("registers a loader per locale under every emitter found in the keys", () => {
    catalog("en", EN);
    catalog("fr", FR);
    expect(run().status).toBe(0);
    const loaders = readFileSync(join(out, "loaders.generated.ts"), "utf8");
    expect(loaders).toContain(
      'type Loader = () => Promise<{ default: Readonly<Record<string, string>> }>;\nexport const LOADERS: Readonly<Record<string, Readonly<Record<string, Loader>>>> = {\n' +
        '  "acme-edge": {\n    "en": () => import("./en.generated.js"),\n    "fr": () => import("./fr.generated.js"),\n  },\n' +
        '  "acme-origin": {\n    "en": () => import("./en.generated.js"),\n    "fr": () => import("./fr.generated.js"),\n  },\n};\n',
    );
  });

  it("omits the copyright line when none is given", () => {
    catalog("en", EN);
    expect(run("--source", source, "--out", out, "--spdx", "LicenseRef-X").status).toBe(0);
    const head = readFileSync(join(out, "en.generated.ts"), "utf8").split("\n").slice(0, 2);
    expect(head).toEqual([
      "// SPDX-License-Identifier: LicenseRef-X",
      `// Generated by embed-error-catalogs from ${source}. Do not edit.`,
    ]);
  });

  it("leaves unchanged files untouched and removes files no longer emitted", () => {
    catalog("en", EN);
    catalog("fr", FR);
    expect(run().status).toBe(0);
    const en = join(out, "en.generated.ts");
    const past = new Date("2020-01-01T00:00:00Z");
    utimesSync(en, past, past);
    writeFileSync(join(out, "stale.generated.ts"), "stale");
    rmSync(join(source, "fr.json"));
    expect(run().status).toBe(0);
    expect(statSync(en).mtime).toEqual(past);
    expect(existsSync(join(out, "stale.generated.ts"))).toBe(false);
    expect(existsSync(join(out, "fr.generated.ts"))).toBe(false);
  });

  it("fails naming the file when en.json is missing", () => {
    catalog("fr", FR);
    const result = run();
    expect(result.status).toBe(1);
    expect(result.stderr).toContain(join(source, "en.json"));
    expect(existsSync(out)).toBe(false);
  });

  it("fails naming a key that is not <emitter>.errors.<CODE>", () => {
    catalog("en", { "plain.key": "x" });
    const result = run();
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('catalog key "plain.key" is not <emitter>.errors.<CODE>');
  });

  it("fails with usage when a required flag is missing or an argument is unknown", () => {
    const missing = run("--source", source, "--out", out);
    expect(missing.status).toBe(1);
    expect(missing.stderr).toContain("missing --spdx");
    const unknown = run("--source", source, "--out", out, "--spdx", "MIT", "--bogus", "x");
    expect(unknown.status).toBe(1);
    expect(unknown.stderr).toContain("unexpected argument: --bogus");
  });

  it("fails when the source directory cannot be read", () => {
    const result = run("--source", join(root, "nowhere"), "--out", out, "--spdx", "MIT");
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("nowhere");
  });
});
