#!/usr/bin/env node
// SPDX-License-Identifier: MIT
//
// Embeds an emitter's error catalogs from the one committed source directory,
// so a package carries no second copy.
//
//   embed-error-catalogs --source <dir> --out <dir> --spdx <id> [--copyright <text>]
//
// One module per locale (pure data) plus a loader table of literal dynamic
// imports per emitter, so a consumer fetches only the locales it renders.
// Every `<locale>.json` in the source directory is embedded and every
// `<emitter>.errors.` key prefix is registered; a new locale file needs no
// change here. `<locale>.sources.json` sidecars are translation provenance,
// not catalogs. Unchanged files are left untouched, so repeated runs keep file
// timestamps stable, and files in the output directory that are not emitted
// are removed. `--spdx` and `--copyright` head every emitted file.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const USAGE =
  "usage: embed-error-catalogs --source <dir> --out <dir> --spdx <id> [--copyright <text>]";

function parseArgs(argv) {
  const known = new Set(["--source", "--out", "--spdx", "--copyright"]);
  const values = {};
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (!known.has(flag) || value === undefined || value.startsWith("--")) {
      throw new Error(`${USAGE}\nunexpected argument: ${flag}`);
    }
    values[flag.slice(2)] = value;
  }
  for (const required of ["source", "out", "spdx"]) {
    if (!values[required]) throw new Error(`${USAGE}\nmissing --${required}`);
  }
  return values;
}

function main() {
  const { source, out, spdx, copyright } = parseArgs(process.argv.slice(2));
  const header =
    `// SPDX-License-Identifier: ${spdx}\n` +
    (copyright ? `// ${copyright}\n` : "") +
    `// Generated by embed-error-catalogs from ${source}. Do not edit.\n`;

  const catalogs = {};
  for (const file of readdirSync(source).sort()) {
    const stem = file.slice(0, -".json".length);
    // `<locale>.sources.json` sidecars are translation provenance, not catalogs.
    if (!file.endsWith(".json") || stem.includes(".")) continue;
    catalogs[stem] = JSON.parse(readFileSync(join(source, file), "utf8"));
  }
  if (!catalogs.en) throw new Error(`${join(source, "en.json")} is missing`);

  const emitters = new Set();
  for (const catalog of Object.values(catalogs)) {
    for (const key of Object.keys(catalog)) {
      const match = /^([a-z][a-z0-9-]*)\.errors\./.exec(key);
      if (!match) throw new Error(`catalog key "${key}" is not <emitter>.errors.<CODE>...`);
      emitters.add(match[1]);
    }
  }

  const files = new Map();
  for (const [locale, catalog] of Object.entries(catalogs)) {
    files.set(
      `${locale}.generated.ts`,
      `${header}const catalog: Readonly<Record<string, string>> = ${JSON.stringify(catalog, null, 2)};\nexport default catalog;\n`,
    );
  }
  const loaderLocales = Object.keys(catalogs).sort();
  const table = [...emitters]
    .sort()
    .map((emitter) => {
      const rows = loaderLocales
        .map((locale) => `    ${JSON.stringify(locale)}: () => import(${JSON.stringify(`./${locale}.generated.js`)}),`)
        .join("\n");
      return `  ${JSON.stringify(emitter)}: {\n${rows}\n  },`;
    })
    .join("\n");
  files.set(
    "loaders.generated.ts",
    `${header}type Loader = () => Promise<{ default: Readonly<Record<string, string>> }>;\nexport const LOADERS: Readonly<Record<string, Readonly<Record<string, Loader>>>> = {\n${table}\n};\n`,
  );

  mkdirSync(out, { recursive: true });
  for (const name of readdirSync(out)) if (!files.has(name)) rmSync(join(out, name), { recursive: true, force: true });
  for (const [name, text] of files) {
    const path = join(out, name);
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) writeFileSync(path, text);
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
