// Embeds the platform error catalogs from the one committed source,
// api-bones-i18n/catalogs/errors, so the package carries no second copy.
// One module per locale (pure data) plus a loader table of literal dynamic
// imports, so a consumer fetches only the locales it renders.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "api-bones-i18n", "catalogs", "errors");
const out = join(here, "..", "src", "error-catalogs");
const BASE = "en";
const HEADER = "// SPDX-License-Identifier: MIT\n// Generated by scripts/embed-catalogs.mjs from api-bones-i18n/catalogs/errors. Do not edit.\n";

const catalogs = {};
for (const file of readdirSync(source).sort()) {
  const stem = file.slice(0, -".json".length);
  if (!file.endsWith(".json") || stem.includes(".")) continue;
  catalogs[stem] = JSON.parse(readFileSync(join(source, file), "utf8"));
}
if (!catalogs[BASE]) throw new Error("catalogs/errors/en.json is missing");

// The platform locale list is the one in the module that negotiates over it.
const module = readFileSync(join(here, "..", "src", "error-localization.ts"), "utf8");
const listed = /export const PLATFORM_LOCALES[^=]*=\s*\[([^\]]*)\]/.exec(module);
if (!listed) throw new Error("PLATFORM_LOCALES not found in src/error-localization.ts");
const platform = [...listed[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const loaderLocales = Object.keys(catalogs).filter((locale) => locale !== BASE).sort();
const expected = platform.filter((locale) => locale !== BASE).sort();
if (JSON.stringify(loaderLocales) !== JSON.stringify(expected)) {
  throw new Error(
    `loader locales [${loaderLocales}] differ from PLATFORM_LOCALES minus ${BASE} [${expected}]`,
  );
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const [locale, catalog] of Object.entries(catalogs)) {
  writeFileSync(
    join(out, `${locale}.generated.ts`),
    `${HEADER}const catalog: Readonly<Record<string, string>> = ${JSON.stringify(catalog, null, 2)};\nexport default catalog;\n`,
  );
}
const entries = loaderLocales
  .map((locale) => `  ${JSON.stringify(locale)}: () => import(${JSON.stringify(`./${locale}.generated.js`)}),`)
  .join("\n");
writeFileSync(
  join(out, "loaders.generated.ts"),
  `${HEADER}export const LOADERS: Readonly<Record<string, () => Promise<{ default: Readonly<Record<string, string>> }>>> = {\n${entries}\n};\n`,
);
